#!/usr/bin/env node
/**
 * Writes client/src/environments/environment.generated.ts from root .env ports.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadProjectEnv, repoRoot } from './env.mjs';

const env = loadProjectEnv();
const outPath = join(repoRoot, 'client/src/environments/environment.generated.ts');

const contents = `/* Auto-generated by scripts/sync-client-env.mjs — do not edit by hand. */
export const generatedEnv = {
  apiBaseUrl: ${JSON.stringify(env.API_BASE_URL)},
  clientPort: ${Number(env.CLIENT_PORT)},
  serverPort: ${Number(env.SERVER_PORT)},
} as const;
`;

writeFileSync(outPath, contents, 'utf8');
console.log(
  `[sync-client-env] api=${env.API_BASE_URL} clientPort=${env.CLIENT_PORT} serverPort=${env.SERVER_PORT}`,
);
